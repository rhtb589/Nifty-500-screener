"""
Incremental OHLCV refresh for all NIFTY 500 stocks.

Only the days missing since each stored file's last entry are fetched —
existing history is never re-downloaded. First run (or a deleted CSV)
backfills the full 1-year window. Set FULL_REFRESH=1 to force a complete
period="1y" refetch (e.g. after a corporate-action adjustment).

Technical indicator columns already present in a file are dropped on
write; compute_indicators.py regenerates them from the merged OHLCV.
"""

import os
import time
import pandas as pd
import yfinance as yf

# Paths
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
CSV_PATH = os.path.join(BASE_DIR, "nifty_500_data.csv")
STOCK_DATA_DIR = os.path.join(BASE_DIR, "stock_data")

# Columns kept from yfinance daily history; anything else in an existing
# file (technical indicators) is stale-on-write and regenerated later.
BASE_COLS = ["Open", "High", "Low", "Close", "Volume", "Dividends", "Stock Splits"]


def get_ticker_list():
    """Read tickers from the main dataset."""
    df = pd.read_csv(CSV_PATH, index_col=0)
    return sorted(df.index.tolist())


def _align_tz(df, tz):
    """Put df's index into the given timezone.

    CSV round-trips parse dates as a fixed offset (UTC+05:30) while yfinance
    returns a zone (Asia/Kolkata). Concatenating mixed tz types silently
    downgrades the index to a plain object Index, so normalise first.
    """
    if df.index.tz is None:
        df = df.copy()
        df.index = df.index.tz_localize(tz)
    elif df.index.tz != tz:
        df = df.copy()
        df.index = df.index.tz_convert(tz)
    return df


def _trim_one_year(df):
    """Keep the trailing 1-year window (same span as yfinance period="1y")."""
    if df.empty:
        return df
    if not isinstance(df.index, pd.DatetimeIndex):
        df = df.copy()
        df.index = pd.to_datetime(df.index)
    if df.index.tz is None:
        cutoff = (pd.Timestamp.now() - pd.DateOffset(years=1)).normalize()
    else:
        cutoff = (pd.Timestamp.now(tz=df.index.tz) - pd.DateOffset(years=1)).normalize()
    return df[df.index >= cutoff]


def download_stock(ticker, interval="1d"):
    """Fetch OHLCV for one ticker, only the days missing from the stored file.

    Returns (df, note):
      df   -> DataFrame to write, or None when yfinance has no data at all
      note -> short summary of what was fetched
    """
    filepath = os.path.join(STOCK_DATA_DIR, f"{ticker}.csv")
    full_refresh = os.environ.get("FULL_REFRESH", "0") == "1"

    old = None
    if os.path.exists(filepath) and not full_refresh:
        try:
            candidate = pd.read_csv(filepath, index_col=0, parse_dates=True)
            if len(candidate) > 0:
                if not isinstance(candidate.index, pd.DatetimeIndex):
                    candidate.index = pd.to_datetime(candidate.index)
                old = candidate
        except Exception:
            old = None  # unreadable/corrupt file -> backfill from scratch

    stock = yf.Ticker(ticker)

    # First run / missing file / FULL_REFRESH -> full 1-year window.
    if old is None:
        hist = stock.history(period="1y", interval=interval)
        if hist.empty:
            return None, "no data"
        hist.index.name = "Date"
        reason = "FULL_REFRESH" if full_refresh else "no stored file"
        return hist, f"full download ({reason}, {len(hist)} rows)"

    last = old.index.max()
    last_date = last.tz_localize(None).date() if last.tz is not None else last.date()

    # Only the days from the last stored entry onward (inclusive of that
    # entry so a partially captured final bar gets refreshed).
    new = stock.history(start=last_date, interval=interval)

    # Keep base columns only — stale indicator columns are regenerated by
    # compute_indicators.py.
    old = old[[c for c in BASE_COLS if c in old.columns]]

    if new is None or new.empty:
        return old.sort_index(), f"up to date (last entry {last_date})"

    new.index.name = "Date"
    # Align index timezone representations before any index operation.
    tz = new.index.tz if new.index.tz is not None else old.index.tz
    old = _align_tz(old, tz)
    new = _align_tz(new, tz)

    added = len(new.index.difference(old.index))
    combined = pd.concat([old, new])
    combined = combined[~combined.index.duplicated(keep="last")]
    combined = combined.sort_index()
    combined = _trim_one_year(combined)
    return combined, f"from {last_date}: +{added} new bar(s)"


def main():
    # Create stock_data directory
    os.makedirs(STOCK_DATA_DIR, exist_ok=True)

    tickers = get_ticker_list()
    total = len(tickers)
    success = 0
    failed = []
    added_total = 0

    print(f"Refreshing OHLCV (missing days only) for {total} stocks...")
    print(f"Output directory: {STOCK_DATA_DIR}")
    print(f"FULL_REFRESH={os.environ.get('FULL_REFRESH', '0')}\n")

    for i, ticker in enumerate(tickers, 1):
        try:
            df, note = download_stock(ticker)
            if df is not None and len(df) > 0:
                filepath = os.path.join(STOCK_DATA_DIR, f"{ticker}.csv")
                df.to_csv(filepath)
                success += 1
                if "new bar(s)" in note:
                    added_total += int(note.rsplit("+", 1)[1].split(" ")[0])
                print(f"[{i}/{total}] {ticker}: {note} ({len(df)} rows)")
            else:
                failed.append(ticker)
                print(f"[{i}/{total}] No data for {ticker}")
        except Exception as e:
            failed.append(ticker)
            print(f"[{i}/{total}] Error downloading {ticker}: {e}")

        # Small delay to avoid rate limiting
        if i % 50 == 0:
            time.sleep(1)

    print(f"\n{'='*50}")
    print(f"Refresh complete: {success}/{total} stocks, {added_total} new bar(s) added")
    if failed:
        print(f"Failed ({len(failed)}): {', '.join(failed[:20])}")


if __name__ == "__main__":
    main()
